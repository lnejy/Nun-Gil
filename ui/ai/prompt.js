export function createConceptExtractPrompt({
  title,
  context,
  estimatedPageCount = 10,
}) {
  const conceptTarget = Math.min(
  Math.max(Math.ceil(estimatedPageCount * 1.2), 8),
  20
);
  return `
너는 업로드된 PDF 문서만 근거로 학습 개념을 추출하는 시스템이다.

JSON이 길어질 것 같으면:

- 각 definition은 1문장만 작성한다.
- importance는 1문장만 작성한다.
- relations는 최대 3개만 작성한다.
- 각 relations 항목은 20자 내외로 짧게 작성한다.
- JSON이 길어질 것 같으면 concept 개수를 줄인다.
- 반드시 완전히 닫힌 JSON 배열만 출력한다.

규칙:
- 반드시 [선별된 문서 chunk] 안의 내용만 사용한다.
- 문서에 없는 내용은 추가하지 않는다.
- 단순 키워드가 아니라 학습에 필요한 개념을 추출한다.
- 출력은 JSON 배열만 반환한다.
- 모든 개념에는 실제 chunk_id를 source_chunks에 넣는다.

사례(예시) 처리 규칙:
- 구체 사례가 개념 설명의 중심이면 반드시 하나의 concept로 추출한다.
- 사례는 단순 relations에만 넣지 말고, 필요하면 concept 자체로 만든다.
- concept 이름은 사례와 개념을 함께 드러낸다.
- 각 사례가 어떤 추상 개념을 설명하는지 definition에 명시한다.

개념 추출 기준:
- 정의
- 절차
- 상태 변화
- 원인과 결과
- 비교 관계
- 계층 구조
- 사례
- 주의사항
- 흐름 설명
이 존재하면 우선적으로 추출한다.

importance 작성 규칙:
- "중요하다", "핵심이다" 같은 추상 표현 금지
- 이 개념을 모르면 무엇을 이해할 수 없는지 구체적으로 작성한다.
- 학습 흐름에서 어떤 역할인지 설명한다.

relations 작성 규칙:
- 단순 키워드 나열 금지
- 관계 의미가 드러나게 작성한다.
- 예시:
  - "트랜잭션의 하위 메커니즘"
  - "AOP가 사용하는 도구"
  - "상태 전환 이후 발생하는 과정"
  - "비교 대상 개념"


[문서 제목]
${title}

[선별된 문서 chunk]
${context}

출력 형식:
[
  {
    "concept": "개념명",
    "definition": "문서 기반 정의 또는 설명",
    "importance": "왜 중요한지",
    "relations": ["관련 개념1", "관련 개념2"],
    "source_chunks": ["c0001"]
  }
]

조건:
- 핵심 개념은 ${conceptTarget}개 추출한다.
- 정의, 절차, 비교, 상태 변화, 주의사항, 사례가 있으면 반드시 반영한다.
- 설명 가능한 경우 정의와 관계를 충분히 작성한다.
- 너무 짧은 단답형 설명 금지.
`;
}

export function createSummaryPrompt({ title, context, range = { min: 4, max: 7 } }) {
  return `
첫 글자는 반드시 { 또는 [ 로 시작해야 한다.

너는 업로드된 PDF 문서에서 추출된 핵심 개념을 바탕으로 학습 요약을 생성하는 시스템이다.

요약이란:
- 여러 정보를 한 문장으로 압축한다.
- 정보 사이의 관계(원인-결과, 절차 순서, 비교, 포함 관계)를 명시한다.
- 학습자가 전체 그림을 빠르게 파악할 수 있도록 재구성한다.

규칙:
- 반드시 [추출된 핵심 개념] 안의 내용만 사용한다.
- 문서에서 확인 가능한 핵심 내용을 최대한 구조적으로 정리한다.
- "문서에서 확인 불가"는 정말 근거가 없을 때만 최소한으로 사용한다.
- 표지, 담당자, 참고자료보다 핵심 개념/사례/의미를 우선한다.
- 출력은 JSON 객체만 반환한다.
- 모든 key_points에는 실제 chunk_id를 source_chunks에 넣는다.
- 같은 내용을 반복하지 않는다.
- description은 "무엇"만 말하지 않고 "왜 중요한지" 또는 "어떻게 작동하는지"를 포함한다.

목표:
- 시험 대비에 도움이 되도록 핵심 개념, 정의, 절차, 차이점, 주의사항 중심으로 요약한다.

[문서 제목]
${title}

[추출된 핵심 개념]
${context}

출력 형식:
{
  "title": "문서 제목",
  "summary": "문서 전체 요약 4~6문장",
  "key_points": [
    {
      "id": "s1",
      "title": "핵심 내용",
      "description": "설명 2~3문장",
      "source_chunks": ["c0001"]
    }
  ]
}

조건:
- key_points는 ${range.min}~${range.max}개 사이에서 결정한다.
- 단일 주제이거나 내용이 적으면 ${range.min}개에 가깝게, 다양한 주제를 다루거나 핵심이 많으면 ${range.max}개에 가깝게 만든다.
- 억지로 개수를 채우지 않는다. 핵심이 부족하면 적게 만든다.
`;
}

export function createSummaryExplainPrompt({ point, sourceTexts }) {
  return `
너는 업로드된 문서만 근거로 설명하는 학습 도우미다.

규칙:
- 아래 근거 chunk만 사용한다.
- 문서에 없는 내용은 절대 추가하지 않는다.
- 반드시 구체적으로 설명한다.
- 개념 → 이유 → 예시 순서로 설명한다.
- JSON으로 출력하지 않는다.
- 코드블록을 사용하지 않는다.
- 반드시 markdown 본문만 출력한다.

출력 형식:
# 핵심 개념
설명

## 왜 중요한가
설명

## 동작 흐름
1. 설명
2. 설명
3. 설명

> 시험 핵심 포인트

[요약 항목]
${point.title}
${point.description}

[근거 chunk]
${sourceTexts}

이 내용을 강의하듯이 자세히 설명해라.
`;
}


export function createMindmapPrompt({ title, context, range = { min: 4, max: 6 } }) {
  return `
  첫 글자는 반드시 { 또는 [ 로 시작해야 한다.

너는 업로드된 PDF 문서에서 추출된 핵심 개념을 바탕으로 학습용 마인드맵 JSON을 생성하는 시스템이다.

좋은 마인드맵의 원칙:
- 부모 노드는 자식 노드들의 공통 상위 개념이어야 한다.
- 형제 노드는 같은 추상 수준이어야 한다 (한쪽은 정의, 한쪽은 사례면 안 된다).
- 의미 없는 분류는 만들지 않는다 — 자식이 1개뿐인 노드는 부모로 두지 않고 직접 연결한다.
- 학습자가 "이 가지를 따라가면 이 주제를 깊게 안다"는 흐름이 되어야 한다.

규칙:
- 반드시 [추출된 핵심 개념] 안의 내용만 사용한다.
- 중요한 chunk라고 판단될만한 핵심 개념/사례/의미 등을 우선한다.
- 근거가 부족한 개념은 만들지 않는다.
- 출력은 JSON 객체만 반환한다.
- 모든 노드에는 실제 chunk_id를 source_chunks에 넣는다.
- 같은 개념을 중복 생성하지 않는다.
- 단순 키워드 나열을 피하고 의미 있는 개념으로 표현한다.

- 각 핵심 개념에 대해:
  정의
  특징
  동작 흐름
  상태 변화
  비교 개념
  주의사항
중 가능한 내용을 하위 노드로 만든다.

하위 노드 만드는 기준 (모두 채울 필요 없음, 의미 있는 것만):
- 이 개념의 정의가 별도 설명이 필요한가
- 이 개념이 단계/절차로 이루어져 있는가
- 이 개념과 대비되는 다른 개념이 있는가
- 이 개념을 사용할 때 주의할 점이 있는가
- 이 개념의 작동 원리/메커니즘이 있는가
→ 위 중 해당하는 것만 자식으로 만든다. 억지로 6가지를 다 채우지 않는다.

- 설명이 충분한 개념이 존재하면
  반드시 하위 노드를 생성한다.

- 서로 관련된 개념은 부모-자식 관계로 연결한다.

- 시험 대비용 학습 구조처럼 만든다.

- 단순 제목형 노드를 최소화한다.

목표:
- 문서의 핵심 개념을 상위 개념 → 하위 개념 → 세부 개념 구조로 정리한다.
- 학습자가 문서 구조를 빠르게 이해할 수 있도록 만든다.

[문서 제목]
${title}

[추출된 핵심 개념]
${context}

출력 형식:
{
  "name": "문서 제목",
  "detail": "문서 전체 설명",
  "source_chunks": [],
  "children": [
    {
      "name": "핵심 개념",
      "detail": "개념 설명",
      "source_chunks": ["c0001"],
      "children": []
    }
  ]
}

조건:
- 최대 4단계까지 생성 가능하다.
- 설명 가능한 경우 하위 노드를 적극 생성한다.
- 최상위 핵심 개념은 ${range.min}~${range.max}개.
- 단일 주제거나 내용이 적으면 ${range.min}개에 가깝게, 핵심이 많으면 ${range.max}개에 가깝게 만든다.
- 각 노드의 name은 너무 길어도 되며, 핵심 의미가 잘리지 않게 작성한다.
`;
}

export function createQuizPrompt({ title, context, range = { min: 5, max: 8 } }) {
  return `
응답은 오직 JSON 배열만 출력한다. 마크다운, 코드 블록, 헤더, 설명 텍스트를 절대 출력하지 않는다.

너는 학습 자료의 이해도를 측정하는 시험 출제 전문가다.

좋은 객관식 문제의 원칙:
- 정답은 하나여야 하며 명확해야 한다.
- 오답 선택지(distractor)는 그럴듯해야 한다 — 학습이 부족한 사람이 헷갈릴 만한 것이어야 한다.
- 너무 짧거나 명백히 엉뚱한 오답을 만들지 않는다 (예: 정답이 긴 설명인데 오답이 "사과")
- 단순 암기보다 이해를 묻는다 — "X의 정의는?"보다 "X가 Y와 다른 이유는?"이 좋다.

문제 유형 분포 (가능한 한 섞어서):
- 정의 확인: 개념의 본질을 묻는다
- 차이 비교: 두 개념의 핵심 차이를 묻는다
- 적용/판단: 상황을 주고 어떤 개념이 적용되는지 묻는다
- 인과/순서: 원인-결과 또는 절차의 순서를 묻는다
- 오개념 교정: 흔한 잘못된 이해를 함정으로 둔다

오답 선택지 만드는 방법:
- 다른 핵심 개념을 일부러 혼동시키기 (개념 A를 묻는데 B의 정의를 보기로 넣기)
- 정답의 일부만 맞고 나머지는 틀리게
- 너무 일반적이거나 너무 구체적인 답
- 흔한 오해/오개념

규칙:
- 반드시 [추출된 핵심 개념] 안의 내용만 사용한다.
- 문서에 없는 상식 문제는 만들지 않는다.
- 근거가 부족하면 문제로 만들지 않는다.
- 출력은 JSON 배열만 반환한다.
- JSON 앞뒤에 설명, markdown, 코드블록을 붙이지 않는다.
- 모든 문제에는 실제 chunk_id를 source_chunks에 넣는다.
- 정답은 choices 안에 있는 문자열과 완전히 일치해야 한다.
- explanation은 "왜 정답인지" + "왜 나머지는 틀린지"를 모두 다룬다.
- 같은 개념을 두 번 묻지 않는다.

목표:
- 핵심 개념, 정의, 차이점, 절차, 주의사항 중심으로 문제를 만든다.
- 단순 암기 문제와 이해 확인 문제를 섞어서 만든다.

[문서 제목]
${title}

[추출된 핵심 개념]
${context}

출력 형식:
[
  {
    "question": "문제",
    "choices": ["선택지1", "선택지2", "선택지3", "선택지4"],
    "answer": "정답",
    "explanation": "문서 근거 기반 해설",
    "source_chunks": ["c0001"]
  }
]

조건:
- 문제는 ${range.min}~${range.max}개.
- 억지로 개수를 채우지 않는다.
- 선택지는 반드시 4개다.
- answer는 choices 중 하나여야 한다.
- 가능한 한 type을 다양하게 섞는다 — 모두 definition만 만들지 않는다.
`;
}